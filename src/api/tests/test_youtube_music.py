sys.path.insert(0, str(Path(__file__).parents[1]))

spec = importlib.util.spec_from_file_location("wave_youtube", Path(__file__).parents[1] / "youtube-music.py")
youtube = importlib.util.module_from_spec(spec)
spec.loader.exec_module(youtube)

ID = "abcdefghijk"
ID2 = "lmnopqrstuv"
AUTH = {"Cookie": "SAPISID=test-session; __Secure-3PAPISID=test-session", "X-Goog-AuthUser": "0"}


def song(video_id=ID, **overrides):
    return {"videoId": video_id, "title": "Song", "artists": [{"name": "Artist", "id": "UC_artist"}],
            "album": {"name": "Album", "id": "MPREb_album"}, "duration": "3:05",
            "thumbnails": [{"url": "https://example.com/small.jpg", "width": 60},
                           {"url": "https://example.com/large.jpg", "width": 400}], **overrides}


class BridgeTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.client = Mock()
        self.client.get_account_info.return_value = {"accountName": "Test account"}
        self.bridge = youtube.MusicBridge(self.temp.name, client_factory=lambda headers: self.client)
        self.bridge.dispatch("save_auth", {"auth": AUTH}, "POST")

    def test_auth_is_private_and_has_fixed_origin(self):
        headers = json.loads(self.bridge.auth_file.read_text())
        self.assertEqual(self.bridge.auth_file.stat().st_mode & 0o777, 0o600)
        self.assertEqual(headers["origin"], "https://music.youtube.com")
        self.assertEqual(headers["authorization"], "SAPISIDHASH")
        status = self.bridge.dispatch("status", {})
        self.assertTrue(status["authorized"])
        self.assertNotIn("cookie", status)

    def test_failed_replacement_preserves_working_session_and_cache(self):
        before = self.bridge.auth_file.read_text()
        self.bridge.track(song())
        self.client.get_account_info.side_effect = KeyError("logged out")
        with self.assertRaises(youtube.ApiError) as error:
            self.bridge.dispatch("save_auth", {"auth": AUTH}, "POST")
        self.assertEqual(error.exception.status, 401)
        self.assertEqual(self.bridge.auth_file.read_text(), before)
        self.assertIn(ID, self.bridge.meta)

    def test_raw_browser_headers_and_json_accept_mixed_case(self):
        raw = "Cookie: SAPISID=test\nX-Goog-AuthUser: 0\nAuthorization: SAPISIDHASH old"
        for value in (raw, json.dumps(AUTH)):
            headers = youtube.parse_auth(value)
            self.assertIn("SAPISID=", headers["cookie"])
            self.assertEqual(headers["authorization"], "SAPISIDHASH")

    def test_auth_rejects_header_injection_and_oauth_files(self):
        for value in ({**AUTH, "Cookie": "SAPISID=secret\r\nHost: attacker"}, {"access_token": "token"}, [], ""):
            with self.subTest(value=value), self.assertRaises(youtube.ApiError):
                youtube.parse_auth(value)

    def test_mutations_require_post(self):
        for action in youtube.MUTATIONS:
            with self.subTest(action=action), self.assertRaises(youtube.ApiError) as error:
                self.bridge.dispatch(action, {})
            self.assertEqual(error.exception.status, 405)

    def test_track_normalization_and_unavailable_tracks(self):
        track = self.bridge.track(song())
        self.assertEqual(track["time"], 185)
        self.assertEqual(track["artistId"], "UC_artist")
        self.assertEqual(track["albumId"], "MPREb_album")
        self.assertEqual(track["image"], "https://example.com/large.jpg")
        self.assertEqual(track["file"], "http://127.0.0.1:8766/youtube/stream/" + ID)
        self.assertIsNone(self.bridge.track(song(isAvailable=False)))
        self.assertIsNone(self.bridge.track(song(video_id="../../etc/passwd")))

    def test_text_filter_is_opt_in_and_does_not_match_studio(self):
        settings = {**youtube.DEFAULT_SETTINGS, "hideAiKeywords": False}
        self.assertFalse(youtube.is_filtered(song(title="AI-generated by Suno"), settings))
        settings["hideAiKeywords"] = True
        self.assertTrue(youtube.is_filtered(song(title="AI-generated by Suno"), settings))
        self.assertTrue(youtube.is_filtered(song(description="Made with Udio"), settings))
        self.assertFalse(youtube.is_filtered(song(title="Live in the studio"), settings))
        self.assertTrue(youtube.is_filtered(song(title="Музыка нейросети"), settings))

    def test_artist_blocks_match_any_contributor_by_name_or_id(self):
        for block in ("artist", "UC_ARTIST"):
            settings = {**youtube.DEFAULT_SETTINGS, "blockedArtists": [block]}
            self.assertTrue(youtube.is_filtered(song(), settings))
            self.assertFalse(youtube.is_filtered(song(artists=[{"name": "Artist Two", "id": "UC_other"}]), settings))

    def test_settings_survive_restart_and_bad_settings_do_not_overwrite(self):
        settings = {"hideAiKeywords": True, "aiKeywords": [" suno ", "suno"], "blockedArtists": ["UC_artist"]}
        self.bridge.dispatch("save_settings", settings, "POST")
        recreated = youtube.MusicBridge(self.temp.name, client_factory=lambda headers: self.client)
        self.assertEqual(recreated.settings["aiKeywords"], ["suno"])
        with self.assertRaises(youtube.ApiError):
            self.bridge.dispatch("save_settings", {**settings, "hideAiKeywords": "false"}, "POST")
        self.assertEqual(recreated.settings, json.loads(self.bridge.settings_file.read_text()))

    def test_pagination_advances_past_a_fully_filtered_page(self):
        self.bridge.settings = {**youtube.DEFAULT_SETTINGS, "hideAiKeywords": True}
        items = [song(title="Suno AI-generated") for _ in range(50)] + [song(ID2, title="Human song")]
        self.client.get_playlist.side_effect = lambda playlist_id, limit: {"title": "Test", "tracks": items[:limit]}
        first = self.bridge.dispatch("get_playlist", {"id": "PL_test"})
        self.assertEqual(first["tracks"], [])
        self.assertEqual(first["hiddenCount"], 50)
        self.assertTrue(first["hasMore"])
        self.assertEqual(first["nextOffset"], 50)
        second = self.bridge.dispatch("get_playlist", {"id": "PL_test", "offset": first["nextOffset"]})
        self.assertEqual([track["id"] for track in second["tracks"]], [ID2])
        self.assertFalse(second["hasMore"])

    def test_filters_cover_search_home_album_playlist_and_radio(self):
        self.bridge.settings = {**youtube.DEFAULT_SETTINGS, "hideAiKeywords": True}
        items = [song(), song(ID2, title="Suno track")]
        self.client.search.return_value = items
        self.client.get_home.return_value = [{"title": "Home", "contents": items}]
        self.client.get_album.return_value = {"title": "Album", "tracks": items}
        self.client.get_playlist.return_value = {"title": "Playlist", "tracks": items}
        self.client.get_watch_playlist.return_value = {"tracks": items}
        for action, params in (("search", {"query": "Artist"}), ("get_album", {"id": "MPREb_album"}),
                               ("get_playlist", {"id": "PL_test"}), ("get_radio", {"id": ID})):
            with self.subTest(action=action):
                result = self.bridge.dispatch(action, params)
                self.assertEqual([track["id"] for track in result["tracks"]], [ID])
                self.assertEqual(result["hiddenCount"], 1)
        home = self.bridge.dispatch("get_home", {})["sections"][0]
        self.assertEqual([track["id"] for track in home["tracks"]], [ID])

    def test_lyrics_and_like_mutations_use_supported_library_contract(self):
        self.client.get_watch_playlist.return_value = {"lyrics": "MPLYt_test"}
        self.client.get_lyrics.return_value = {"lyrics": "A line", "source": "LyricFind", "hasTimestamps": False}
        self.assertEqual(self.bridge.dispatch("get_lyrics", {"id": ID})["lyrics"], "A line")
        self.bridge.dispatch("rate_song", {"id": ID, "rating": "LIKE"}, "POST")
        self.client.rate_song.assert_called_once_with(ID, youtube.LikeStatus.LIKE)
        with self.assertRaises(youtube.ApiError):
            self.bridge.dispatch("rate_song", {"id": ID, "rating": "INVALID"}, "POST")

    def test_expired_session_reports_auth_failure_without_leaking_upstream_text(self):
        self.client.get_account_info.side_effect = youtube.YTMusicServerError("Server returned HTTP 401: Secret cookie")
        with self.assertRaises(youtube.ApiError) as error:
            self.bridge.dispatch("status", {})
        self.assertEqual(error.exception.status, 401)
        self.assertNotIn("Secret", str(error.exception))

    def test_batch_metadata_skips_unavailable_track(self):
        self.bridge.track(song())
        self.client.get_song.return_value = {"videoDetails": {}}
        result = self.bridge.dispatch("batch_get_meta", {"ids": [ID, ID2]}, "POST")
        self.assertEqual(result[ID]["title"], "Song")
        self.assertIsNone(result[ID2])

    def test_disconnect_removes_session_and_disables_new_audio(self):
        self.bridge.dispatch("disconnect", {}, "POST")
        self.assertFalse(self.bridge.auth_file.exists())
        self.assertFalse(self.bridge.dispatch("status", {})["authorized"])
        with self.assertRaises(youtube.ApiError) as error:
            self.bridge.audio(ID)
        self.assertEqual(error.exception.status, 401)

    def test_audio_resolves_to_audio_only_and_reuses_short_lived_link(self):
        self.bridge.runtime = ("node", "/usr/bin/node")
        downloader = Mock()
        downloader.extract_info.return_value = {"url": "https://cdn.googlevideo.com/audio", "vcodec": "none", "http_headers": {}}
        with patch.object(youtube, "YoutubeDL") as constructor:
            constructor.return_value.__enter__.return_value = downloader
            first = self.bridge.audio(ID)
            self.assertIs(first, self.bridge.audio(ID))
            self.bridge.audio(ID, refresh=True)
        self.assertEqual(downloader.extract_info.call_count, 2)
        downloader.extract_info.assert_called_with("https://music.youtube.com/watch?v=" + ID, download=False)

    def test_prepare_track_does_not_expose_audio_urls_or_credentials(self):
        with patch.object(self.bridge, "audio", return_value={"url": "https://cdn.googlevideo.com/secret"}) as audio:
            result = self.bridge.dispatch("prepare_track", {"id": ID}, "POST")
        self.assertEqual(result, {"status": "ok", "track": None})
        audio.assert_called_once_with(ID)

    def test_audio_retries_with_full_page_when_fast_extraction_fails(self):
        self.bridge.runtime = ("node", "/usr/bin/node")
        downloader = Mock(params=self.bridge.extractor_options())
        downloader.extract_info.side_effect = [youtube.DownloadError("Fast extraction failed"),
            {"url": "https://cdn.googlevideo.com/audio", "vcodec": "none", "http_headers": {}}]
        with patch.object(youtube, "YoutubeDL") as constructor:
            constructor.return_value.__enter__.return_value = downloader
            self.bridge.audio(ID)
        self.assertEqual(downloader.extract_info.call_count, 2)
        self.assertEqual(downloader.params["extractor_args"], {})

    def test_unknown_home_duration_is_resolved_without_overwriting_artist_or_album(self):
        self.bridge.track(song(duration="0"))
        self.client.get_song.return_value = {"videoDetails": {"lengthSeconds": "245"}}
        track = self.bridge.dispatch("get_meta", {"id": ID})
        self.assertEqual(track["time"], 245)
        self.assertEqual(track["artist"], "Artist")
        self.assertEqual(track["album"], "Album")
        self.bridge.track(song(duration="0"))
        self.assertEqual(self.bridge.meta[ID]["time"], 245)


class AudioRelayTests(unittest.TestCase):
    def handler(self, method="GET", range_value=None):
        handler = object.__new__(youtube.Handler)
        handler.path = "/youtube/stream/" + ID
        handler.command = method
        handler.headers = {"Range": range_value} if range_value else {}
        handler.wfile = BytesIO()
        handler.send_response = Mock()
        handler.send_header = Mock()
        handler.end_headers = Mock()
        handler.json_response = Mock()
        bridge = Mock()
        bridge.audio.return_value = {"url": "https://cdn.googlevideo.com/audio", "headers": {"User-Agent": "test"}, "size": 4}
        handler.server = SimpleNamespace(bridge=bridge)
        return handler

    def response(self, status=206):
        response = Mock()
        response.status_code = status
        response.headers = {"Content-Type": "audio/mp4", "Content-Length": "4", "Accept-Ranges": "bytes", "Content-Range": "bytes 0-3/4"}
        response.iter_content.return_value = [b"data"]
        return response

    def test_mpd_seek_range_and_audio_bytes_are_forwarded(self):
        handler = self.handler(range_value="bytes=100-")
        handler.server.bridge.audio.return_value["size"] = 104
        response = self.response(206)
        response.headers["Content-Range"] = "bytes 100-103/104"
        with patch.object(youtube.requests, "get", return_value=response) as request:
            handler.serve_audio()
        self.assertEqual(request.call_args.kwargs["headers"]["Range"], "bytes=100-103")
        handler.send_response.assert_called_once_with(206)
        handler.send_header.assert_any_call("Content-Range", "bytes 100-103/104")
        self.assertEqual(handler.wfile.getvalue(), b"data")
        response.close.assert_called_once()

    def test_head_does_not_copy_audio_body(self):
        handler = self.handler(method="HEAD")
        response = self.response()
        with patch.object(youtube.requests, "get", return_value=response):
            handler.serve_audio()
        self.assertEqual(handler.wfile.getvalue(), b"")
        response.iter_content.assert_not_called()
        response.close.assert_called_once()

    def test_expired_audio_link_is_refreshed_once(self):
        handler = self.handler()
        first, second = self.response(403), self.response()
        with patch.object(youtube.requests, "get", side_effect=[first, second]):
            handler.serve_audio()
        self.assertEqual(handler.server.bridge.audio.call_count, 2)
        handler.server.bridge.audio.assert_called_with(ID, refresh=True)
        self.assertEqual(handler.wfile.getvalue(), b"data")
        first.close.assert_called_once()

    def test_complete_audio_is_joined_from_bounded_ranges(self):
        handler = self.handler()
        handler.server.bridge.audio.return_value["size"] = 12
        responses = []
        for start, data in ((0, b"abcd"), (4, b"efgh"), (8, b"ijkl")):
            response = self.response()
            response.headers["Content-Range"] = f"bytes {start}-{start + 3}/12"
            response.iter_content.return_value = [data]
            responses.append(response)
        with patch.object(youtube, "AUDIO_CHUNK_SIZE", 4), patch.object(youtube.requests, "get", side_effect=responses) as request:
            handler.serve_audio()
        self.assertEqual([call.kwargs["headers"]["Range"] for call in request.call_args_list], ["bytes=0-3", "bytes=4-7", "bytes=8-11"])
        self.assertEqual(handler.wfile.getvalue(), b"abcdefghijkl")
        handler.send_response.assert_called_once_with(200)
        handler.send_header.assert_any_call("Content-Length", "12")

    def test_truncated_range_resumes_without_repeating_audio_bytes(self):
        handler = self.handler()
        handler.server.bridge.audio.return_value["size"] = 8
        responses = []
        for content_range, data in (("bytes 0-3/8", b"ab"), ("bytes 2-5/8", b"cdef"), ("bytes 6-7/8", b"gh")):
            response = self.response()
            response.headers["Content-Range"] = content_range
            response.iter_content.return_value = [data]
            responses.append(response)
        with patch.object(youtube, "AUDIO_CHUNK_SIZE", 4), patch.object(youtube.requests, "get", side_effect=responses):
            handler.serve_audio()
        self.assertEqual(handler.wfile.getvalue(), b"abcdefgh")

    def test_suffix_and_invalid_seek_ranges(self):
        self.assertEqual(youtube.audio_byte_range("bytes=-4", 12), (8, 11, 206))
        self.assertEqual(youtube.audio_byte_range("bytes=4-999", 12), (4, 11, 206))
        for value in ("bytes=12-", "bytes=6-2", "bytes=-0", "bytes=-"):
            with self.assertRaises(youtube.ApiError):
                youtube.audio_byte_range(value, 12)

    def test_path_traversal_and_multi_ranges_never_reach_upstream(self):
        for path, range_value in (("/youtube/stream/../../etc/passwd", None), ("/youtube/stream/" + ID, "bytes=0-1,5-6")):
            handler = self.handler(range_value=range_value)
            handler.path = path
            with patch.object(youtube.requests, "get") as request:
                handler.serve_audio()
            request.assert_not_called()
            handler.json_response.assert_called_once()


